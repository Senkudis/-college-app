const PptxGenJS = require('pptxgenjs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'عرض-نظام-كلية-النصر-التقنية.pptx');

/* ===== هوية بصرية مشتقة من التطبيق نفسه =====
   0D3B66 هو theme-color في manifest التطبيق، و2176C7 لون البانر الرئيسي.
   العرض يستخدم ألوان المنتج لا ألوان عامة. */
const NAVY   = '0D3B66';
const BLUE   = '2176C7';
const AMBER  = 'F59E0B';
