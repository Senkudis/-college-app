const WHITE  = 'FFFFFF';
const GREEN  = '1B6B47';

const FONT = 'Arial'; // تغطية عربية كاملة ومقاسات موثوقة

const pres = new PptxGenJS();
pres.layout = 'LAYOUT_WIDE';           // 13.3 × 7.5 بوصة
pres.rtlMode = true;
pres.author = 'كلية النصر التقنية';
pres.title = 'نظام كلية النصر التقنية الرقمي';

const W = 13.3, H = 7.5;
const M = 0.7;                          // هامش موحّد

/* نص عربي: RTL ومحاذاة لليمين افتراضياً */
const T = (o = {}) => ({ isTextBox: true, rtlMode: true, align: 'right', fontFace: FONT, ...o });

/* ترويسة موحّدة لكل شريحة محتوى */
function head(slide, title, kicker) {
  if (kicker) {
    slide.addText(kicker, T({
      x: M, y: 0.42, w: W - M * 2, h: 0.3,
      fontSize: 12, bold: true, color: BLUE, charSpacing: 1
    }));
  }
  slide.addText(title, T({
    x: M, y: kicker ? 0.72 : 0.55, w: W - M * 2, h: 0.75,
    fontSize: 34, bold: true, color: NAVY
  }));
}

/* بطاقة محتوى — الشكل المتكرر عبر العرض (المحفّز البصري) */
function card(slide, { x, y, w, h, icon, title, body, tone = WHITE, accent = BLUE }) {
  slide.addShape(pres.ShapeType.roundRect, {
    x, y, w, h, rectRadius: 0.12,
    fill: { color: tone },
    line: { color: tone === WHITE ? 'DCE3EB' : tone, width: 1 },
    shadow: { type: 'outer', angle: 90, blur: 10, offset: 2, color: '0D3B66', opacity: 0.10 }
  });
  if (icon) {
    slide.addShape(pres.ShapeType.ellipse, {
      x: x + w - 0.92, y: y + 0.22, w: 0.52, h: 0.52,
      fill: { color: accent }, line: { color: accent, width: 0 }
    });
    slide.addText(icon, T({
      x: x + w - 0.92, y: y + 0.22, w: 0.52, h: 0.52,
      fontSize: 20, bold: true, color: WHITE, align: 'center', valign: 'middle', margin: 0
    }));
  }
  slide.addText(title, T({
    x: x + 0.25, y: y + 0.28, w: w - (icon ? 1.3 : 0.5), h: 0.42,
    fontSize: 16, bold: true, color: NAVY, margin: 0
  }));
  if (body) {
    slide.addText(body, T({
      x: x + 0.25, y: y + 0.76, w: w - 0.5, h: h - 1.0,
      fontSize: 12.5, color: MUTED, margin: 0, lineSpacing: 18
    }));
  }
}

/* رقم كبير مع تسمية */
function stat(slide, { x, y, w, num, label, color = BLUE }) {
  slide.addText(num, T({
    x, y, w, h: 0.95, fontSize: 54, bold: true, color, align: 'center', margin: 0
  }));
  slide.addText(label, T({
    x, y: y + 0.92, w, h: 0.45, fontSize: 12.5, color: MUTED, align: 'center', margin: 0
  }));
}

